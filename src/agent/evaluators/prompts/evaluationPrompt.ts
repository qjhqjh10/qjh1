  '   - 中文表述是否流畅自然？',
  '',
  '3. **architecture** (架构, 权重 0.2):',
  '   - 文件位置是否符合项目结构规范？',
  '   - 命名是否符合约定？是否引入了不必要的依赖？',
  '   - 是否使用了正确的工具？操作是否高效？',
  '',
  '4. **security** (安全, 权重 0.15):',
