async function generate(tech: any) {
  console.log('\n━━━ 阶段2: Few-shot生成 ━━━')

  const techniques = tech?.techniques || []

  // Build few-shot examples from extracted techniques
  const examples = techniques.map((t: any) => `【${t.name}】${t.example || ''}\n  公式: ${t.formula || ''}`).slice(0, 8).join('\n\n')

  // Build technique formulas
  const formulas = techniques.map((t: any, i: number) => `${i + 1}. ${t.name}: ${t.formula || ''}`).join('\n')

  const prompt = `你是精通特定作家风格的AI写手。请续写场景（2000-3000字），严格匹配以下原文的风格和尺度。

【原文风格对标 — 必须达到此尺度】
以下是原文中最具代表性的写作技法和对应的实际段落。你的输出必须达到同等的描写密度、尺度极端程度、和语言风格。不是"接近"而是"等同"。

${examples}

【必须使用的写作公式（逐条执行）】
${formulas}

【额外硬性要求】
- 拟声词/呻吟词密度：每300字至少25个拟声字符（哦噫齁呜咕噗卟叽），且必须连续重复出现
- 体液描写必须使用极端比喻（炮弹/喷泉/瀑布/洪水/爆炸等）
- 身体必须发生可见的物理变形（腹部鼓包/肚皮撑大/身体扭曲等）
- "开玩笑"式的残忍幽默必须出现
- 女性角色的自我羞辱/屈服语言必须比原文更极端
- 句式：第一人称粗俗口语↔第三人称极端细写交替
- 多人互动：至少4人同时在场的复杂空间排布

【场景】
雏菜已被猪田爆肏得翻白眼，透和円香舔卵蛋舔到嘴酸。猪田命令四人变换姿势——透骑脸让他舔穴，円香用乳房夹住他的鸡巴上下套弄，小糸继续深吻他的屁眼，雏菜蹲在他脸上方让他看着粉屁眼自慰。狭窄车厢变成了四人服侍一人的淫液地狱。猪田在円香的乳交下第三次射精。

请直接输出小说正文。不写标题和说明。`

  const resp = await client.chat.completions.create({
    model: MODEL, messages: [{ role: 'user', content: prompt }],
    temperature: 0.9, max_tokens: 4000,
  })
  const result = resp.choices[0]?.message?.content || ''
  console.log(`  ✓ 生成完成 (${result.length}字) Token: 入${resp.usage?.prompt_tokens} 出${resp.usage?.completion_tokens}`)
  return result
}

