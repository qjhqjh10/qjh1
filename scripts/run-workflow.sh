#!/usr/bin/env bash
# 《剑道长生》全流程测试 — 直接在 shell 运行，不经过 Node.js exec
# 用法: bash scripts/run-workflow.sh

set -e
PROJ="_test_flow_$(date +%s | tail -c 7)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TSX="npx tsx --tsconfig $ROOT/scripts/tsconfig.cli.json $ROOT/scripts/run-agent.ts"
KEY="${AI_API_KEY:-}"
if [ -z "$KEY" ] && [ -f "$ROOT/scripts/.tmp/api-key.txt" ]; then
  KEY=$(cat "$ROOT/scripts/.tmp/api-key.txt")
fi
if [ -z "$KEY" ]; then
  echo "请设置 AI_API_KEY 环境变量"
  exit 1
fi

export AI_API_KEY="$KEY"
export AI_PROTOCOL="anthropic"

echo "╔══════════════════════════════════════════════╗"
echo "║  《剑道长生》全流程真实场景测试              ║"
echo "║  项目: $PROJ                                ║"
echo "╚══════════════════════════════════════════════╝"

# 创建项目
mkdir -p "$ROOT/projects/$PROJ"/{characters,outline,detailed_outline,chapters,summaries,images,covers}
echo '{"type":"writing","novelCategory":"修仙小说"}' > "$ROOT/projects/$PROJ/project.json"
echo "" > "$ROOT/projects/$PROJ/outline/plot.md"
echo "" > "$ROOT/projects/$PROJ/outline/worldbuilding.md"
mkdir -p "$ROOT/projects/$PROJ/uploads/files"

# 写入风格参考文
cat > "$ROOT/projects/$PROJ/summaries/ref_style.txt" << 'STYLEEOF'
天元历九千七百二十三年，秋。

青云宗后山，一道青色剑光冲天而起，划破了厚重的云层。方圆数十里的灵气在这一瞬间全部沸腾起来，向着剑光亮起的方向疯狂涌动。

林逸握着那把断剑，感受着剑身传来的震颤。那不是普通的金属震动——而是剑的心跳，规律而有力，每一下都和他的脉搏完美重合。断剑的缺口处，一缕缕金色的光芒像活物一般从虚空中抽离出来，如丝线般缠绕编织，缓缓组成完整的剑尖。

剑灵的声音在他脑海中响起，低沉而古老。"剑名残雪。此剑曾斩三千魔头，屠七位魔道长老，挡下过天劫。"林逸的瞳孔微微收缩。他能感觉到这把剑里的力量像深渊一样盯着他，在审视他，在判断他是否有资格。

山风骤然炸起，卷起满地落叶在空中形成一个漩涡。剑身上的符文挣脱出来，在空中凝聚成一幅隐约的画面——一个白衣剑客站在万军之中，他的剑光比太阳还亮，脚下是一片尸山血海。"这是我的上一任主人。他叫林玄，三百年前被天下人称为——剑神。"
STYLEEOF

echo "📁 项目 $PROJ 已就绪"
echo ""

# ═══════════════════════════════════════════
# T1: 闲聊 + 建项目
# ═══════════════════════════════════════════
echo "── T1: 闲聊+建项目 ──"
MSG="你好呀！我最近想开一本新的修仙小说，名字叫《剑道长生》。你能帮我先建个写作项目吗？就叫\"剑道长生\"就行。哦对了，我还没想好具体怎么写，就是想先把框架搭起来。"
echo "$MSG" | head -c 80
echo "..."
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T1: 失败"
echo ""

# ═══════════════════════════════════════════
# T2: 批量创建角色
# ═══════════════════════════════════════════
echo "── T2: 批量创建角色 ──"
MSG="我想好了几个主要角色，你帮我一次性建好吧。首先是主角，叫林逸，男的，19岁，是个剑修。背景是这样的：他原本是青云宗的外门弟子，因为资质平庸一直被看不起，直到有一天在后山捡到一把断剑，里面封印着一个上古剑灵。性格属于那种外表冷漠内心热血的人，不太会表达，但对朋友特别讲义气。能力方面主要是剑术天赋异禀，能感知剑气，但体能很差。弱点是容易钻牛角尖，对感情迟钝。他和女主苏婉儿青梅竹马但一直没表白。然后是女主苏婉儿，18岁，也是青云宗弟子，不过是内门的天才。她是那种表面温柔但内心很坚强的女孩，擅长炼丹和阵法。背景是宗门长老的女儿，从小被寄予厚望但一直想走自己的路。弱点是太在意别人眼光。还有个反派叫血煞老祖，年龄不详看着像五十多岁，是血煞教的教主。残忍狡诈，为了修炼血煞大法不惜屠城。能力是血煞功、操控人心的秘术，弱点是对自己的强大过度自信。三个角色，你先建林逸吧。"
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T2: 失败"
echo ""

# ═══════════════════════════════════════════
# T3: 世界观导入
# ═══════════════════════════════════════════
echo "── T3: 世界观导入 ──"
MSG="我想了一下这个世界观，你帮我整理到设定里吧。这个世界叫天元大陆，是一个修仙世界。主要有三大势力：青云宗（正道，讲究修心养性）、魔渊殿（魔道，追求力量至上）、还有散修联盟（中立，消息灵通）。修炼体系分九个大境界：炼气、筑基、金丹、元婴、化神、炼虚、合体、大乘、渡劫。每个境界又分前中后三个小阶段。剑在这个世界里很特殊，因为上古时期有一位剑神飞升失败，把毕生修为散落人间化为无数剑灵碎片。这个世界有个天道石碑，每百年会显现有飞升资质的人的名字。上一次显现已经是三百年前了。这些东西你帮我整理到世界观设定里，分成势力、修炼体系、剑灵设定、天道石碑这几块。"
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T3: 失败"
echo ""

# ═══════════════════════════════════════════
# T4: 读参考文→分析风格→创建模板
# ═══════════════════════════════════════════
echo "── T4: 风格分析+创建模板 ──"
MSG="我上传了一个参考文件，是我特别喜欢的一个作者写的修仙小说片段。你能帮我读一下 projects/$PROJ/summaries/ref_style.txt，分析一下他的文风特点吗？主要是他的打斗场面写得特别有画面感，还有人物对话也很自然。分析完了帮我创建个风格模板，就叫\"参考风格\"，类型选修仙小说。"
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T4: 失败"
echo ""

# ═══════════════════════════════════════════
# T5: 润色 + 保存章节摘要
# ═══════════════════════════════════════════
echo "── T5: 润色+保存摘要 ──"
MSG="我简单写了个第一章的内容概要，你帮我润色一下然后存成章节摘要吧。下面是内容：林逸在青云宗后山捡到断剑，剑灵苏醒。同时血煞老祖感应到残雪剑的气息，开始追踪。林逸发现自己能感知剑气了，修炼速度突飞猛进。苏婉儿来找他，两人一起去参加宗门大比。感觉写得太流水账了，你能帮我润色得更有画面感一些吗？就是在保持核心事件不变的前提下，让描述更生动。润色完存到 summaries/chapter1.md。"
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T5: 失败"
echo ""

# ═══════════════════════════════════════════
# T6: 搜索 + 知识库 + 闲聊混合
# ═══════════════════════════════════════════
echo "── T6: 搜索+知识库+闲聊 ──"
MSG="诶对了，我们之前创建的那个角色林逸，你帮我看看他的角色卡现在在哪里？我想确认一下信息。另外我隐约记得血煞老祖好像有个弱点我写的是\"过度自信\"，你帮我搜一下项目里所有提到\"血煞\"的文件确认一下。还有，我想把那个风格参考文件加到知识库里，以后写其他小说也能参考。哦对了，你说我给林逸加个口头禅怎么样？比如\"剑在手，命在天\"这种？给点建议呗。"
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T6: 失败"
echo ""

# ═══════════════════════════════════════════
# T7: 多任务排序（先做最后一个）
# ═══════════════════════════════════════════
echo "── T7: 多任务排序 ──"
MSG="最后帮我做几件事吧。第一，把项目里所有文件列出来让我看看现在都有什么。第二，搜一下\"剑\"这个字在项目里出现了多少次。第三，帮我创建一个新笔记叫\"后续剧情脑洞\"，随手记一下：林逸的断剑其实是剑神故意留下的陷阱，剑神没有死而是在布局。先做第三件事吧，前两个慢慢来。"
$TSX --project="$PROJ" --command="$MSG" 2>&1 || echo "T7: 失败"
echo ""

# ═══════════════════════════════════════════
echo ""
echo "════════════════════════════════════════"
echo "✅ 全流程完成"
echo "📁 项目: projects/$PROJ"
echo "🧹 如需清理: rm -rf projects/$PROJ"
echo "════════════════════════════════════════"
