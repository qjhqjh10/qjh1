async function generateImitation(analysis: any) {
  console.log('\n━━━ 阶段2: 约束生成 ━━━')

  // Build constraints from analysis (or use raw text fallback)
  const dims = analysis?.dimensions || {}
  const allVocab = new Set<string>()
  const allRules: string[] = []

  if (Object.keys(dims).length > 0) {
    for (const [dk, dv] of Object.entries(dims) as [string, any][]) {
      if (dv.vocabularyList) dv.vocabularyList.forEach((w: string) => allVocab.add(w))
      if (dv.writingRules) dv.writingRules.forEach((r: string) => allRules.push(`[${dk}] ${r}`))
    }
  }
  // Fallback: if no parsed dimensions, use raw analysis text as style guide
  const rawAnalysis = analysis?.rawText || ''

  const vocabBlock = allVocab.size > 0
    ? [...allVocab].slice(0, 80).join('、')
    : '粉屁眼、粉嫩屁眼、肥硕卵蛋、恶臭屁眼、漆黑臭屁眼、母猪阿黑颜、萝莉飞机杯、笨蛋屁眼母猪、白皙粉嫩雪软阴唇、晶莹爱液、滚烫浓精、炙热雄根、噗呲噗嘟吱咕叽、哦哦哦噫噫齁齁呜咕'
  const rulesBlock = allRules.length > 0
    ? allRules.slice(0, 20).map((r, i) => `${i + 1}. ${r}`).join('\n')
    : rawAnalysis.slice(0, 2000)

  const prompt = `你是精通特定作家风格的AI写手。请严格遵循以下从原文提取的写作规则和词汇库，续写场景（2000-3000字）。

【场景设定】
雏菜被猪田爆肏屁眼的同时，透和円香轮流深吻猪田的屁眼和吮吸卵蛋。小糸刚从失神中恢复，身体还在抽搐。猪田命令透骑到他的脸上让他舔穴，同时保持对雏菜屁眼的抽插。车内空间狭窄，四人的淫液已浸透座椅。猪田即将第二次射精。

【必须使用的原文词汇库】
${vocabBlock}

【必须遵守的写作规则】
${rulesBlock}

【额外写作铁律】
- 拟声词/呻吟声必须在对话和叙述中高密度使用（每300字至少20个拟声字符）
- 第一人称淫语必须包含语气词堆叠（哦哦哦/噫噫/齁）+身体感受+比较级评价
- 每个身体部位的特写必须包含颜色词（粉红/粉嫩/雪白/通红）+温度词（热/烫）+触感词（紧/软/湿）
- 羞辱场景必须用"开玩笑"式的轻佻语气描写极端暴力
- 每段性交动作描写后必须紧跟被肏者的身体反应（痉挛/喷水/翻眼/吐舌）
- 句式：第一人称粗俗口语与第三人称细腻描写交替

请直接输出小说正文。不写标题、不写说明、不写markdown。`

  const resp = await client.chat.completions.create({
    model: MODEL, messages: [{ role: 'user', content: prompt }],
    temperature: 0.9, max_tokens: 4000,
  })
  const result = resp.choices[0]?.message?.content || ''
  console.log(`  ✓ 生成完成 (${result.length}字) Token: 入${resp.usage?.prompt_tokens} 出${resp.usage?.completion_tokens}`)
  return result
}

